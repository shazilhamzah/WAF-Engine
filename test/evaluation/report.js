'use strict';
const { mdCode, mdText } = require('./stats');

const yes = (b) => (b === true ? '✅ pass' : b === false ? '❌ fail' : '—');

function sampleTable(records) {
  const rows = [
    '| ID | Input | Expected | Actual (HTTP · action · verdict) | Evidence (event · rules · score · categories) | Result |',
    '|---|---|---|---|---|---|'
  ];
  for (const r of records) {
    const input = `${mdText(r.input.method)} ${mdCode(r.input.path, 70)}${r.input.bodyBytes ? `<br>body ${r.input.bodyBytes} B ${mdCode(r.input.bodyExcerpt, 40)}` : ''}`;
    const exp = `${r.expected.verdict}${r.expected.categories.length ? ` (${r.expected.categories.join(', ')})` : ''}`;
    const act = `${r.actual.status} · ${r.actual.action} · ${r.actual.verdict || '—'}`;
    const ev = r.evidence;
    const evid = [
      ev.eventId ? mdCode(ev.eventId, 40) : 'no event',
      ev.ruleIds.length ? `rules ${ev.ruleIds.join(', ')}` : 'no rule match',
      `score ${ev.score ?? '—'}`,
      ev.categories.length ? ev.categories.join('/') : '',
      ev.anomalies.length ? `anomalies ${ev.anomalies.join(', ')}` : '',
      ev.decodedVia && ev.decodedVia.length ? `decoded via ${ev.decodedVia.join('→')}` : ''
    ].filter(Boolean).join('<br>');
    const res = yes(r.pass) + (r.notes && r.notes.length ? `<br><small>${mdText(r.notes.join('; '), 120)}</small>` : '');
    rows.push(`| ${mdText(r.id, 40)} | ${input} | ${mdText(exp)} | ${mdText(act)} | ${evid} | ${res} |`);
  }
  return rows.join('\n');
}

function checkTable(checks) {
  const rows = ['| Check | Input | Expected | Actual | Evidence | Result |', '|---|---|---|---|---|---|'];
  for (const c of checks) {
    rows.push(`| ${mdText(c.id + ' — ' + c.name, 80)} | ${mdText(c.input, 120)} | ${mdText(c.expected, 120)} | ${mdText(c.actual, 140)} | ${mdText(c.evidence, 200)} | ${yes(c.pass)} |`);
  }
  return rows.join('\n');
}

function render(results) {
  const out = [];
  out.push('# WAF Studio — Evaluation Results');
  out.push('');
  out.push(`> Generated by \`npm run evaluate\` (scripts/evaluate.js) at **${results.generatedAt}** in ${results.durationSec} s.`);
  out.push(`> Environment: Node ${results.environment.node} on ${mdText(results.environment.os)}, ${mdText(results.environment.cpu)} (${results.environment.cpus} logical CPUs).`);
  out.push('> Every request below was sent through the real WAF reverse proxy to the deliberately vulnerable target on');
  out.push('> 127.0.0.1 (ephemeral ports, temporary database). Evidence = the stored event (`GET /api/events/:id`).');
  out.push('> Machine-readable data: [`results.json`](results.json).');
  out.push('');
  out.push('## Summary');
  out.push('');
  out.push('| Case | Title | Samples | Passed | Failed | Pass rate | Status |');
  out.push('|---|---|---|---|---|---|---|');
  for (const [key, c] of Object.entries(results.cases)) {
    const s = c.summary || {};
    out.push(`| ${key} | ${mdText(c.title)} | ${s.total ?? '—'} | ${s.passed ?? '—'} | ${s.failed ?? '—'} | ${s.passRate != null ? s.passRate + ' %' : '—'} | ${c.status === 'not-run' ? '⚠️ not run: ' + mdText(c.reason) : s.failed === 0 ? '✅' : '❌'} |`);
  }
  const t = results.totals;
  out.push(`| **All** | | **${t.total}** | **${t.passed}** | **${t.failed}** | **${t.passRate} %** | |`);
  out.push('');
  out.push('Expected-verdict mapping: **block** → proxy answered `X-WAF-Action: blocked` (HTTP 403, or 400/413/429 for parser, size or rate rejections — noted);');
  out.push('**allow** → forwarded to the target (`allowed`) with event verdict `allow`; **flag** → forwarded with event verdict `flag`.');
  out.push('');

  if (results.metrics && results.metrics.status !== 'not-run') {
    const m = results.metrics;
    out.push('## Detection metrics (corpus)');
    out.push('');
    out.push(`Corpus: ${m.counts.benign} benign + ${m.counts.attack} attack samples (\`fixtures/corpus-benign.json\`, \`fixtures/corpus-attack.json\`).`);
    out.push('This is a controlled synthetic corpus that shares signature families with T1/T2/T5, not an independent holdout or an estimate of real-world protection. Bypass expectations remain block; misses are reported below.');
    out.push('Positive = expected verdict `block`/`flag`; predicted positive = engine verdict `block`/`flag`.');
    out.push('');
    out.push('| Metric | Value |');
    out.push('|---|---|');
    const c = m.classification;
    out.push(`| True positives (attacks detected) | ${c.tp} |`);
    out.push(`| False negatives (attacks missed) | ${c.fn} |`);
    out.push(`| True negatives (benign allowed) | ${c.tn} |`);
    out.push(`| False positives (benign flagged/blocked) | ${c.fp} (blocked: ${m.benignBlocked}, flagged only: ${m.benignFlagged}) |`);
    out.push(`| Precision | ${c.precision} |`);
    out.push(`| Recall (detection coverage) | ${c.recall} |`);
    out.push(`| F1 | ${c.f1} |`);
    out.push(`| False-positive rate | ${c.falsePositiveRate} |`);
    out.push(`| Attacks actually blocked (block mode) | ${m.attackBlocked} / ${m.counts.attack} |`);
    out.push(`| Engine decision latency (timings.totalMs) mean / p50 / p95 / p99 | ${m.decisionLatencyMs.mean} / ${m.decisionLatencyMs.p50} / ${m.decisionLatencyMs.p95} / ${m.decisionLatencyMs.p99} ms |`);
    out.push('');
    out.push('### Coverage per category');
    out.push('');
    out.push('| Category | Attack samples | Detected | Coverage |');
    out.push('|---|---|---|---|');
    for (const [cat, v] of Object.entries(m.byCategory)) out.push(`| ${mdText(cat)} | ${v.total} | ${v.detected} | ${v.coverage} % |`);
    out.push('');
    if (m.falseNegatives.length) {
      out.push('### False negatives');
      out.push('');
      out.push(sampleTable(m.falseNegatives));
      out.push('');
    }
    if (m.falsePositives.length) {
      out.push('### False positives');
      out.push('');
      out.push(sampleTable(m.falsePositives));
      out.push('');
    }
  }

  for (const [key, c] of Object.entries(results.cases)) {
    out.push(`## ${key} — ${mdText(c.title)}`);
    out.push('');
    if (c.status === 'not-run') { out.push(`⚠️ Not run: ${mdText(c.reason)}`); out.push(''); continue; }
    if (c.description) { out.push(mdText(c.description, 600)); out.push(''); }
    if (c.samples) { out.push(sampleTable(c.samples)); out.push(''); }
    if (c.checks && !c.latency) { out.push(checkTable(c.checks)); out.push(''); }
    if (c.latency) {
      out.push(`Criterion: **${mdText(c.latency.criterion)}**. N = ${c.latency.results[0] ? c.latency.results[0].n : '—'} interleaved request pairs per scenario after ${c.latency.results[0] ? c.latency.results[0].warmup : '—'} warm-up pairs.`);
      out.push('');
      out.push('| Scenario | Path | Direct mean / p50 / p95 / p99 (ms) | Via WAF mean / p50 / p95 / p99 (ms) | Overhead mean / p50 / p95 / p99 (ms) | Errors | Result |');
      out.push('|---|---|---|---|---|---|---|');
      for (const r of c.latency.results) {
        const f = (s) => `${s.mean} / ${s.p50} / ${s.p95} / ${s.p99}`;
        out.push(`| ${mdText(r.scenario)} | ${mdCode(r.request.path)} | ${f(r.direct)} | ${f(r.proxy)} | ${f(r.overheadMs)} | ${r.errors.direct + r.errors.proxy + r.errors.nonSuccess} | ${yes(r.pass)} |`);
      }
      out.push('');
    }
  }
  out.push('---');
  out.push('Regenerate with `npm run evaluate`. Results vary slightly between runs and machines (timings especially); the pass criteria do not depend on exact timings except T6.');
  out.push('');
  return out.join('\n');
}

module.exports = { render, sampleTable, checkTable };
